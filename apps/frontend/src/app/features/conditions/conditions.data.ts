export const CONDITIONS_BY_SLUG: Record<string, ConditionContent> =
  Object.fromEntries(CONDITIONS.map(c => [c.slug, c]));

/** Condition page matching a test category (/test/list/:type), if any. */
export const conditionForTestCategory = (type: string | null | undefined): ConditionContent | undefined =>
  type ? CONDITIONS.find(c => c.testCategory === type) : undefined;

/** Condition page for a test's section (from sectionOf), if the clinic has one. */
export const conditionForTestSection = (section: string | null | undefined): ConditionContent | undefined =>
  section ? CONDITIONS.find(c => c.testSections?.includes(section)) : undefined;

/** First condition page matching one of an article's categories, if any. */
export const conditionForArticleCategories = (cats: string[] | null | undefined): ConditionContent | undefined =>
  CONDITIONS.find(c => c.articleCategory && cats?.some(cat => cat.toLowerCase() === c.articleCategory));
