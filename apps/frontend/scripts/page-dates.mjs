// Writes src/page-dates.generated.ts: for each static page, the date of the last
// commit that touched its source, used as <lastmod> in /sitemap.xml. Runs before
// `ng serve` / `ng build`; the server has no git history at runtime.
//
//   node scripts/page-dates.mjs
//
// The file is committed. Vercel builds from a shallow clone, where git only knows
// pages changed in the last few commits; every other page keeps its committed date.
// Commit the file when a local build changes it.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const features = 'src/app/features';

/** Sitemap path → source paths whose changes count as a page update. */
const PAGES = {
  '/about':      [`${features}/about`],
  '/visit':      [`${features}/visit`],
  '/reviews':    [`${features}/reviews`],
  '/pro-tsentr': [`${features}/center`],
  '/drugs':      [`${features}/drugs`],
  // Every condition page is one component filled from conditions.data.ts.
  conditions:    [`${features}/conditions`],
};

const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

// Vercel clones shallowly; the boundary commit looks like it added every file, so its
// date would be wrong. Try to fetch the full history, and otherwise ignore that commit.
let boundary = new Set();
try {
  if (git('rev-parse', '--is-shallow-repository') === 'true') {
    try { git('fetch', '--unshallow', '--quiet'); } catch { /* no credentials: keep the shallow history */ }
    const shallowFile = resolve(root, git('rev-parse', '--git-path', 'shallow'));
    try { boundary = new Set(readFileSync(shallowFile, 'utf8').split('\n').filter(Boolean)); } catch { /* unshallowed */ }
  }
} catch {
  console.warn('page-dates: no git, sitemap static pages get no lastmod');
}

const out = resolve(root, 'src/page-dates.generated.ts');
let committed = {};
try { committed = JSON.parse(readFileSync(out, 'utf8').match(/=\s*(\{[\s\S]*\});/)[1]); } catch { /* first run */ }

const lastCommit = (paths) => {
  try {
    const [sha, date] = git('log', '-1', '--format=%H %cI', '--', ...paths, ':(exclude)*.spec.ts').split(' ');
    return sha && !boundary.has(sha) ? date.slice(0, 10) : undefined;
  } catch {
    return undefined;
  }
};

const dates = Object.fromEntries(
  Object.entries(PAGES).map(([page, paths]) => [page, lastCommit(paths) ?? committed[page]]).filter(([, d]) => d),
);

writeFileSync(
  out,
  '// Generated by scripts/page-dates.mjs — do not edit.\n'
    + `export const PAGE_DATES: Record<string, string> = ${JSON.stringify(dates, null, 2)};\n`,
);
console.log(`page-dates: ${Object.keys(dates).length}/${Object.keys(PAGES).length} pages dated`);
