// Fetches all tests from the backend and writes a <url> entry for every
// /test/detail/:id page into src/sitemap.xml, between the TESTS:DETAIL markers.
// Usage: npm run sitemap:tests
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const API_TESTS = 'https://mental-clinic-be.onrender.com/api/tests';
const BASE_URL = 'https://doctor-skripnik.com.ua';
const SITEMAP = fileURLToPath(new URL('../src/sitemap.xml', import.meta.url));
const START = '<!-- TESTS:DETAIL:START (generated by scripts/generate-sitemap-tests.mjs) -->';
const END = '<!-- TESTS:DETAIL:END -->';

const res = await fetch(API_TESTS, { signal: AbortSignal.timeout(120_000) });
if (!res.ok) throw new Error(`GET ${API_TESTS} → ${res.status}`);
const tests = await res.json();
if (!Array.isArray(tests) || tests.length === 0) throw new Error('API returned no tests');

const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const entries = tests
  .filter(t => t._id)
  .map(t => [
    `  <!-- ${escape(t.name ?? '').replace(/--/g, '—')} -->`,
    '  <url>',
    `    <loc>${BASE_URL}/test/detail/${encodeURIComponent(t._id)}</loc>`,
    '    <changefreq>monthly</changefreq>',
    '    <priority>0.7</priority>',
    '  </url>',
  ].join('\n'))
  .join('\n\n');

const block = `${START}\n${entries}\n  ${END}`;
let xml = await readFile(SITEMAP, 'utf8');
const pattern = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);

if (pattern.test(xml)) {
  xml = xml.replace(pattern, block);
} else {
  const anchor = '  <!-- ── Supporting pages';
  if (!xml.includes(anchor)) throw new Error('Insertion anchor not found in sitemap.xml');
  xml = xml.replace(anchor, `  ${block}\n\n${anchor}`);
}

await writeFile(SITEMAP, xml);
console.log(`sitemap.xml: ${tests.length} test detail pages`);
