// Fetches tests and published articles from the backend and regenerates the dynamic parts
// of src/sitemap.xml:
//   TESTS:DETAIL — every /test/detail/:id page
//   ARTICLES     — every article (with lastmod) and every article category that has articles
//                  (empty categories are noindex, so they stay out of the sitemap)
// Usage: npm run sitemap
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const API = 'https://mental-clinic-be.onrender.com/api';
const BASE_URL = 'https://doctor-skripnik.com.ua';
const SITEMAP = fileURLToPath(new URL('../src/sitemap.xml', import.meta.url));

// Must match ARTICLE_CATEGORIES in articles-list.component.ts (route slug ← stored name)
const ARTICLE_CATEGORY_SLUGS = ['депресія', 'тривога', 'птср', 'залежності', 'сон', 'стрес'];

const getJson = async url => {
  const res = await fetch(url, { signal: AbortSignal.timeout(120_000) });
  if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
  return res.json();
};

const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const comment = s => `  <!-- ${escape(s ?? '').replace(/--/g, '—')} -->`;
const url = ({ loc, lastmod, changefreq, priority }) => [
  '  <url>',
  `    <loc>${loc}</loc>`,
  ...(lastmod ? [`    <lastmod>${lastmod.slice(0, 10)}</lastmod>`] : []),
  `    <changefreq>${changefreq}</changefreq>`,
  `    <priority>${priority}</priority>`,
  '  </url>',
].join('\n');

const replaceBlock = (xml, name, entries) => {
  const start = `<!-- ${name}:START (generated by scripts/generate-sitemap-tests.mjs) -->`;
  const end = `<!-- ${name}:END -->`;
  const pattern = new RegExp(`${start.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${end}`);
  if (!pattern.test(xml)) throw new Error(`${name} markers not found in sitemap.xml`);
  return xml.replace(pattern, `${start}\n${entries.join('\n\n')}\n  ${end}`);
};

const tests = await getJson(`${API}/tests`);
if (!Array.isArray(tests) || tests.length === 0) throw new Error('API returned no tests');

const articles = (await getJson(`${API}/articles?limit=1000`)).filter(a => a.status === 'published' && (a.slug || a._id));
const usedCategories = new Set(articles.flatMap(a => a.categories ?? []).map(c => c.toLowerCase()));

const testEntries = tests
  .filter(t => t._id)
  .map(t => `${comment(t.name)}\n${url({
    loc: `${BASE_URL}/test/detail/${encodeURIComponent(t._id)}`, changefreq: 'monthly', priority: '0.7',
  })}`);

const articleEntries = [
  ...ARTICLE_CATEGORY_SLUGS
    .filter(slug => usedCategories.has(slug))
    .map(slug => url({ loc: `${BASE_URL}/articles/category/${encodeURIComponent(slug)}`, changefreq: 'weekly', priority: '0.7' })),
  ...articles.map(a => `${comment(a.title)}\n${url({
    loc: `${BASE_URL}/articles/${encodeURIComponent(a.slug ?? a._id)}`,
    lastmod: a.updatedAt ?? a.publishedAt ?? a.createdAt,
    changefreq: 'monthly',
    priority: '0.8',
  })}`),
];

let xml = await readFile(SITEMAP, 'utf8');
xml = replaceBlock(xml, 'TESTS:DETAIL', testEntries);
xml = replaceBlock(xml, 'ARTICLES', articleEntries);
await writeFile(SITEMAP, xml);
console.log(`sitemap.xml: ${tests.length} tests, ${articles.length} articles, ${articleEntries.length - articles.length} article categories`);
